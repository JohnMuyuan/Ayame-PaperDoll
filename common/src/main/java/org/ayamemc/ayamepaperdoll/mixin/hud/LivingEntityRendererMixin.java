package org.ayamemc.ayamepaperdoll.mixin.hud;

import net.minecraft.client.renderer.entity.LivingEntityRenderer;
import net.minecraft.client.renderer.entity.state.LivingEntityRenderState;
import org.ayamemc.ayamepaperdoll.hud.NameTagScaleState;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(LivingEntityRenderer.class)
public class LivingEntityRendererMixin {
    @Inject(method = "shouldRenderLayers", at = @At("HEAD"), cancellable = true)
    private void hideLayersForNameTagOnly(LivingEntityRenderState state, CallbackInfoReturnable<Boolean> cir) {
        if (NameTagScaleState.isNameTagsOnly()) {
            cir.setReturnValue(false);
        }
    }
}
