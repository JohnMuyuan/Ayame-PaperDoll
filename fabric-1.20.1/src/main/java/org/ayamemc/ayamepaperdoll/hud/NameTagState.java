package org.ayamemc.ayamepaperdoll.hud;

/**
 * The paper doll draws its own name tag, so the vanilla one is suppressed while the doll is rendered.
 */
public final class NameTagState {
    private static boolean suppressed = false;

    private NameTagState() {
    }

    public static void setSuppressed(boolean value) {
        suppressed = value;
    }

    public static boolean isSuppressed() {
        return suppressed;
    }
}
